// needsLive is the line every section that could not be measured carries. It is
// deliberately identical everywhere so a reader can tell "zero" from "unknown"
// at a glance — conflating those two is how a coverage document lies.
const needsLive = "_Not measured: this section needs a live ClickHouse connection. Run with `CLICKHOUSE_URL` pointing at a read replica or a `kubectl port-forward` to the ClickHouse pod._"

// Measurement step names, as Repo.Facts reports them. A section built on a step
// that failed prints a warning instead of passing its zeros off as counts —
// "unknown" and "none" are indistinguishable in a table, and telling them apart
// is the entire job of this document.
const (
	stepAssets     = "fresh assets"
	stepKeys       = "asset metadata keys"
	stepBands      = "finding bands"
	stepResources  = "finding resource types"
	stepSources    = "source liveness"
	stepCheckOpen  = "open findings by check"
	stepProducers  = "open findings by category and check"
	stepEdges      = "fresh edges"
	stepMetaValues = "asset metadata values"
)

// warnIfIncomplete emits a caveat when any measurement this section depends on
// failed, naming it.
func warnIfIncomplete(b *strings.Builder, r Report, steps ...string) {
	var hit []string
	for _, want := range steps {
		for _, failed := range r.FailedSteps {
			if failed == want {
				hit = append(hit, failed)
			}
		}
	}
	if len(hit) == 0 {
		return
	}
	fmt.Fprintf(b, "> **Incomplete.** The %s measurement did not complete, so the numbers below are\n"+
		"> floors, not counts. Do not read a zero here as an absence.\n\n", join(hit, len(hit)))
}

// Render turns a Report into the markdown of docs/COVERAGE.md.
func Render(r Report) string {
	var b strings.Builder
	renderHeader(&b, r)
	renderMethod(&b, r)
	renderScope(&b, r)
	renderAxes(&b)
	renderCategories(&b, r)
	renderLineage(&b, r)
	renderAdvisory(&b, r)
	renderSources(&b, r)
	renderChecks(&b, r)
	renderUnreadKeys(&b, r)
	renderEdges(&b, r)
	renderTargets(&b, r)
	return b.String()
}

func renderHeader(b *strings.Builder, r Report) {
	b.WriteString("# Coverage\n\n")
	b.WriteString("<!-- Generated by cmd/coverage-gen. DO NOT EDIT. -->\n\n")
	b.WriteString("Detection posture across the four axes on which coverage fails. Every number here\n")
	b.WriteString("is derived — from the checks registry, the `internal/graphschema` edge registry, an\n")
	b.WriteString("AST scan of this tree, and live ClickHouse counts — so \"are we covered?\" is a\n")
	b.WriteString("query, and a regression is a diff in a pull request rather than a rediscovery six\n")
	b.WriteString("months later. Regenerate with `go run ./cmd/coverage-gen`.\n\n")
	mode := "**live** — registry-derived sections plus measured ClickHouse counts"
	if !r.Live {
		mode = "**offline** — registry-derived sections only"
	}
	fmt.Fprintf(b, "Generated %s. Mode: %s.\n\n", r.GeneratedAt.Format(time.RFC3339), mode)
	if r.LiveErr != "" {
		fmt.Fprintf(b, "> Live data unavailable or partial: `%s`\n\n", r.LiveErr)
	}
}

func renderMethod(b *strings.Builder, r Report) {
	b.WriteString("## Method\n\n")
	b.WriteString("Stated because this document will be trusted, and a count whose method is unstated\n")
	b.WriteString("is an opinion.\n\n")
	b.WriteString("| Quantity | Definition |\n|---|---|\n")
	b.WriteString("| dedup | every ReplacingMergeTree read this report makes dedups with `argMax`: `assets` and `findings` by `argMax(col, synced_at) … GROUP BY id`, `finding_enrichment` by `argMax(col, enriched_at) … GROUP BY id`, and `graph_edges` as the edge dedup row states. None of its queries uses `FINAL`. |\n")
	fmt.Fprintf(b, "| open finding | `resolved_at = toDateTime(0)` |\n")
	fmt.Fprintf(b, "| fresh asset | `%s`, applied after dedup, where high_water is that PROVIDER's own most recent last_seen (never wall-clock — a stalled collector must read as \"this provider's data is stale\", not as its whole estate vanishing) |\n", AssetFreshness)
	fmt.Fprintf(b, "| fresh edge | `%s` — `graph_edges` is never deleted, only re-stamped, so an unfiltered reader resurrects topology that no longer exists |\n", graphschema.EdgeFreshnessCond)
	b.WriteString("| edge dedup | `GROUP BY src_id, edge_type, dst_id` with `max(synced_at)`, matching the table's ORDER BY |\n")
	b.WriteString("| evidence coverage | per-key presence measured independently; a check's coverage is reported as the presence of its WORST required key, which is an upper bound on \"assets carrying all of them\", stated as a bound rather than dressed up as an exact figure |\n")
	b.WriteString("| check required keys | `Check.RequiredKeys`, derived from the predicate AST by `internal/checks/keyscan` — never hand-written, so it cannot drift from the predicate it describes |\n")
	b.WriteString("| evidence vs suppressor key | a required key is *evidence-bearing* when, with every other required key present, some value of it would have fired a predicate that stayed silent without it — decided by `Check.Evaluable`, not declared. The rest are *suppressors*: keys read only to exempt the check (`ns_psa_enforce` on the k8s pod checks, `archived` on `github-no-branch-protection`), absent by design, and their absence never prevented the check concluding. Only evidence keys can constitute an evidence gap; advising a collector to emit a suppressor would turn the check OFF where it fires today. |\n")
	b.WriteString("| which check answers for a category | the checks that ACTUALLY produced the category's open findings, joined on `check_id` — not every check that happens to share a resource type. Categories whose findings carry no registry check ID say the evidence axis does not apply rather than borrowing an unrelated check's gap. |\n\n")
	if !r.Live {
		b.WriteString(needsLive + "\n\n")
	}
}

func renderScope(b *strings.Builder, r Report) {
	b.WriteString("## Scope\n\n")
	warnIfIncomplete(b, r, stepAssets)
	b.WriteString("| Provider | Weighted | Why | Fresh assets |\n|---|---|---|---|\n")
	for _, s := range ProviderScopes {
		count := "_not measured_"
		if r.Live {
			count = fmt.Sprintf("%d", r.FreshAssets[s.Provider])
		}
		fmt.Fprintf(b, "| %s | %s | %s | %s |\n", s.Provider, yesNo(s.Weighted), s.Reason, count)
	}
	b.WriteString("\n")
}

func renderAxes(b *strings.Builder) {
	b.WriteString("## The four axes\n\n")
	b.WriteString("Every coverage gap fails on exactly one of these, and from outside they all look\n")
	b.WriteString("identical — silence. They are a pipeline: fixing a later axis while an earlier one\n")
	b.WriteString("is broken changes nothing, so a category is assigned the FIRST axis that fails.\n\n")
	b.WriteString("| Axis | Symptom | Rule that assigns it |\n|---|---|---|\n")
	for _, a := range Axes {
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", a.Axis, a.Symptom, a.Rule)
	}
	b.WriteString("\nNo per-category judgement is applied. Two runs that disagree, disagree because the\ndata changed.\n\n")
}

func renderCategories(b *strings.Builder, r Report) {
	b.WriteString("## Coverage by finding category\n\n")
	warnIfIncomplete(b, r, stepBands, stepResources, stepAssets, stepKeys, stepEdges, stepProducers)
	if !r.Live {
		b.WriteString(needsLive + "\n\n")
		return
	}
	b.WriteString("One row per `source` × `type`, ordered by open volume.\n\n")
	b.WriteString("| Source | Type | Open | blank must_fix | page | high | Axis | Because |\n|---|---|---:|---:|---:|---:|---|---|\n")
	for _, c := range r.Categories {
		fmt.Fprintf(b, "| %s | %s | %d | %.0f%% (%d) | %.0f%% (%d) | %.0f%% (%d) | `%s` | %s |\n",
			c.Source, c.Type, c.Open, c.BlankPct(), c.Blank, c.PagePct(), c.Page, c.HighPct(), c.High, c.Axis, c.Because)
	}
	b.WriteString("\n")
	renderAxisTotals(b, r)
}

func renderAxisTotals(b *strings.Builder, r Report) {
	open := map[Axis]uint64{}
	cats := map[Axis]int{}
	for _, c := range r.Categories {
		open[c.Axis] += c.Open
		cats[c.Axis]++
	}
	b.WriteString("Open findings by failing axis:\n\n| Axis | Categories | Open findings |\n|---|---:|---:|\n")
	for _, a := range append(axisList(), AxisCovered) {
		fmt.Fprintf(b, "| `%s` | %d | %d |\n", a, cats[a], open[a])
	}
	b.WriteString("\n")
}

func axisList() []Axis {
	out := make([]Axis, 0, len(Axes))
	for _, a := range Axes {
		out = append(out, a.Axis)
	}
	return out
}

func renderLineage(b *strings.Builder, r Report) {
	b.WriteString("## The lineage chain\n\n")
	warnIfIncomplete(b, r, stepAssets, stepEdges)
	b.WriteString("`repo → asset → exposed → which packages, from where`. This is the headline\n")
	b.WriteString("because it breaks in the MIDDLE, not at the ends: both endpoints are well\n")
	b.WriteString("populated and every join between them loses an order of magnitude.\n\n")
	if !r.Live {
		b.WriteString(needsLive + "\n\n")
		return
	}
	b.WriteString("| Stage | Measured as | Count | Of stage | What a zero would mean |\n|---|---|---:|---:|---|\n")
	for _, s := range r.Stages {
		measured := fmt.Sprintf("fresh assets of %s", join(s.Types, 4))
		switch s.Kind {
		case StageEdgeSrc:
			measured = fmt.Sprintf("distinct sources of fresh `%s`", s.EdgeType)
		case StageEdgeDst:
			measured = fmt.Sprintf("distinct destinations of fresh `%s`", s.EdgeType)
		case StageAssetMeta:
			measured += fmt.Sprintf(" where `%s` is %s", s.MetaKey, strings.Join(s.MetaValues, " or "))
		case StageAssets:
		}
		if len(s.Types) > 0 && s.Kind != StageAssets && s.Kind != StageAssetMeta {
			measured += fmt.Sprintf(" where the endpoint is %s", join(s.Types, 4))
		}
		share := "—"
		if s.OfStage != "" {
			share = fmt.Sprintf("%.1f%% of %s", s.Pct(), s.OfStage)
		}
		fmt.Fprintf(b, "| %s | %s | %d | %s | %s |\n", s.Name, measured, s.Count, share, s.Question)
	}
	b.WriteString("\n")
}

func renderSources(b *strings.Builder, r Report) {
	b.WriteString("## Source liveness\n\n")
	warnIfIncomplete(b, r, stepSources)
	b.WriteString("A source is *declared* when this tree can produce it: a `finding.Finding`\n")
	b.WriteString("composite literal setting `Source` to a string constant, or a package-level\n")
	b.WriteString("`…Sources` allowlist (how the external-scanner import path expresses it). The\n")
	b.WriteString("scan is mechanical, so a source that exists only in someone's mental model\n")
	b.WriteString("cannot appear here, and one that exists in code but has never fired cannot hide.\n\n")
	if !r.Live {
		b.WriteString("| Source | Declared in code |\n|---|---|\n")
		for _, s := range r.Sources {
			fmt.Fprintf(b, "| %s | %s |\n", s.Source, yesNo(s.Declared))
		}
		b.WriteString("\n" + needsLive + "\n\n")
		return
	}
	b.WriteString("| Source | Declared | Open | Total | Last produced | Days stale |\n|---|---|---:|---:|---|---:|\n")
	now := r.GeneratedAt
	for _, s := range r.Sources {
		last, stale := "never", "—"
		if d := s.StaleDays(now); d >= 0 {
			last = s.LastDetected.Format("2006-01-02")
			stale = fmt.Sprintf("%d", d)
		}
		fmt.Fprintf(b, "| %s | %s | %d | %d | %s | %s |\n", s.Source, yesNo(s.Declared), s.Open, s.Total, last, stale)
	}
	b.WriteString("\n")
	var silent []string
	for _, s := range r.Sources {
		if s.Declared && s.Total == 0 {
			silent = append(silent, s.Source)
		}
	}
	if len(silent) > 0 {
		fmt.Fprintf(b, "Declared but never produced anything: %s.\n\n", join(silent, len(silent)))
	}
}

func renderChecks(b *strings.Builder, r Report) {
	b.WriteString("## Detection checks and their evidence\n\n")
	warnIfIncomplete(b, r, stepAssets, stepKeys, stepCheckOpen)
	structural := 0
	for _, c := range r.Checks {
		if c.StructuralOnly() {
			structural++
		}
	}
	fmt.Fprintf(b, "%d registered checks; %d decide on structural asset fields alone and so cannot\nfail the evidence axis. The rest read asset metadata, and the keys they read are\nderived from their predicates' AST.\n\n", len(r.Checks), structural)
	if !r.Live {
		b.WriteString("| Check | Provider | Asset type | Severity | Required keys |\n|---|---|---|---|---|\n")
		for _, c := range r.Checks {
			fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s |\n", c.ID, c.Provider, orDash(c.AssetType), c.Severity, keyList(c.RequiredKeys))
		}
		b.WriteString("\n" + needsLive + " (evidence coverage and open counts)\n\n")
		return
	}
	b.WriteString("Ordered by evidence gap: the worst evidence-bearing key first. A check at 100% has\nevery such key present on every fresh asset it applies to. Suppressor keys are\nexcluded — their absence is the design, not a gap.\n\n")
	b.WriteString("| Check | Asset type | Applicable | Worst evidence key | Present | Bound | Open |\n|---|---|---:|---|---:|---:|---:|\n")
	sorted := append([]CheckFact(nil), r.Checks...)
	sort.Slice(sorted, func(a, z int) bool {
		if sorted[a].EvidenceBound() != sorted[z].EvidenceBound() {
			return sorted[a].EvidenceBound() < sorted[z].EvidenceBound()
		}
		return sorted[a].ID < sorted[z].ID
	})
	var suppressorOnly []string
	for _, c := range sorted {
		if c.EvidenceBlind() {
			if !c.StructuralOnly() {
				suppressorOnly = append(suppressorOnly, c.ID)
			}
			continue
		}
		fmt.Fprintf(b, "| `%s` | %s | %d | `%s` | %d | %.1f%% | %d |\n",
			c.ID, orDash(c.AssetType), c.Applicable, c.WorstKey, c.WorstKeyPresent, 100*c.EvidenceBound(), c.OpenFindings)
	}
	b.WriteString("\n")
	if len(suppressorOnly) > 0 {
		sort.Strings(suppressorOnly)
		fmt.Fprintf(b, "Checks whose every required key is a suppressor — read only to exempt the check,\nso no absence of them can be an evidence gap: %s.\n\n", join(suppressorOnly, len(suppressorOnly)))
	}
	if len(r.EmptyAssetTypes) > 0 {
		fmt.Fprintf(b, "Asset types a registered check targets that hold zero fresh assets — the\n`collected` axis at check granularity: %s.\n\n", join(r.EmptyAssetTypes, len(r.EmptyAssetTypes)))
	}
}

func renderUnreadKeys(b *strings.Builder, r Report) {
	b.WriteString("## Metadata collected but never asserted on\n\n")
	warnIfIncomplete(b, r, stepAssets, stepKeys)
	b.WriteString("The `check` axis, measured. A key counts only when the registry reads it\n")
	b.WriteString("*somewhere* — that is the platform's own evidence that the key is assertable —\n")
	b.WriteString("and no check for this provider/type reads it. Keys nothing reads anywhere are\n")
	b.WriteString("descriptive metadata (an ARN, a timestamp) and are excluded.\n\n")
	if !r.Live {
		b.WriteString(needsLive + "\n\n")
		return
	}
	if r.UnreadKeyTotal == 0 {
		b.WriteString("None: every assertable key present on a fresh asset is read by a check for that\nprovider and type.\n\n")
		return
	}
	fmt.Fprintf(b, "%d such keys; the %d widest by asset count:\n\n", r.UnreadKeyTotal, len(r.UnreadKeys))
	b.WriteString("| Provider | Asset type | Key | Assets | Read by, elsewhere |\n|---|---|---|---:|---|\n")
	for _, k := range r.UnreadKeys {
		fmt.Fprintf(b, "| %s | %s | `%s` | %d | `%s` |\n", k.Provider, k.AssetType, k.Key, k.Assets, k.ReadBy[0])
	}
	b.WriteString("\n")
}

func renderEdges(b *strings.Builder, r Report) {
	b.WriteString("## The graph axis: the edge pipeline\n\n")
	warnIfIncomplete(b, r, stepEdges)
	b.WriteString("From `internal/graphschema`, the single source of truth for the edge\n")
	b.WriteString("pipeline. An edge type that is unsynced, or feeds a rel that is not loaded,\n")
	b.WriteString("cannot carry a hop count no matter how many rows ClickHouse holds — which is why\n")
	b.WriteString("row volume alone never answered \"can scoring reach this?\".\n\n")
	b.WriteString("| Edge type | Rel | Tier | Reach | Inherit | Loaded | Expand | Fresh rows | Distinct src | Drop reason |\n|---|---|---|---|---|---|---|---:|---:|---|\n")
	for _, e := range r.Edges {
		rows, dsrc := "—", "—"
		if e.LiveKnown {
			rows, dsrc = fmt.Sprintf("%d", e.Rows), fmt.Sprintf("%d", e.DistinctSrc)
		}
		fmt.Fprintf(b, "| `%s` | %s | %s | %s | %s | %s | %s | %s | %s | %s |\n",
			e.Type, orDash(e.Rel), e.Tier, yesNo(e.Reach), yesNo(e.Inherit), yesNo(e.Loaded), yesNo(e.Expand),
			rows, dsrc, firstLine(e.DropReason))
	}
	b.WriteString("\n")
	if !r.Live {
		b.WriteString(needsLive + " (row volumes)\n\n")
	}
}

func renderTargets(b *strings.Builder, r Report) {
	b.WriteString("## What 100% means\n\n")
	warnIfIncomplete(b, r, stepBands, stepResources, stepProducers)
	b.WriteString("Per category, the concrete condition that would close it — derived from the axis\n")
	b.WriteString("it fails on, not asserted. Where the answer is a product decision rather than\n")
	b.WriteString("engineering, it says so instead of inventing a threshold.\n\n")
	if !r.Live {
		b.WriteString(needsLive + "\n\n")
		renderStaticTargets(b)
		return
	}
	b.WriteString("| Source | Type | Open | Axis | Condition that closes it |\n|---|---|---:|---|---|\n")
	for _, c := range r.Categories {
		note := c.Target
		if c.NeedsDecision {
			note = "**Decision, not engineering.** " + note
		}
		fmt.Fprintf(b, "| %s | %s | %d | `%s` | %s |\n", c.Source, c.Type, c.Open, c.Axis, note)
	}
	b.WriteString("\n")
	var blank, routine uint64
	for _, c := range r.Categories {
		blank += c.Blank
		routine += c.Routine
	}
	fmt.Fprintf(b, "Closing every axis above admits the %d open findings that currently carry no\n"+
		"`must_fix_class` at all into banding, on top of the %d already classed `routine`\n"+
		"(weighed, no urgency evidence). How much of that lands in the high band, and whether\n"+
		"that volume is acceptable, is not derivable from coverage data: it is a decision\n"+
		"about the band thresholds, and this document deliberately does not invent one.\n\n", blank, routine)
	renderStaticTargets(b)
}

func renderStaticTargets(b *strings.Builder) {
	b.WriteString("Per axis, the general condition:\n\n")
	b.WriteString("| Axis | 100% means |\n|---|---|\n")
	b.WriteString("| `collected` | every asset type a registered check targets has fresh rows |\n")
	b.WriteString("| `evidence` | every evidence-bearing `Check.RequiredKey` is present on every fresh asset its check applies to — evidence bound 100% for every row of the check table. Suppressor keys are excluded by construction: emitting one would suppress the check |\n")
	b.WriteString("| `check` | the \"metadata collected but never asserted on\" table is empty |\n")
	b.WriteString("| `graph` | every resource type carrying an open finding is the source of at least one fresh reach-set, inherit or internet-seed edge |\n\n")
}

func yesNo(v bool) string {
	if v {
		return "yes"
	}
	return "no"
}

func orDash(s string) string {
	if s == "" {
		return "—"
	}
	return s
}

func keyList(keys []string) string {
	if len(keys) == 0 {
		return "_none — structural_"
	}
	return "`" + strings.Join(keys, "`, `") + "`"
}

// firstLine keeps a registry Doc/DropReason from breaking the markdown table it
// lands in: those fields carry multi-sentence histories.
func firstLine(s string) string {
	if s == "" {
		return "—"
	}
	s = strings.ReplaceAll(s, "\n", " ")
	s = strings.ReplaceAll(s, "|", "/")
	if idx := strings.Index(s, ". "); idx > 0 {
		s = s[:idx+1]
	}
	if len(s) > 160 {
		s = s[:157] + "…"
	}
	return s
}
