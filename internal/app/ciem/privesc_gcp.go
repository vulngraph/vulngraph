package ciem

// GCPPrivescRules returns the full catalog of GCP IAM privilege escalation
// detection rules, drawn from Rhino Security Labs GCP research.
func GCPPrivescRules() []PrivescRule {
	return []PrivescRule{
		{ID: "gcp-privesc-01", Technique: TechniqueGCPSetIAMPolicy, Severity: SeverityCritical,
			Description:     "Set IAM policy on project/org to grant self Owner or Editor role",
			RequiredActions: []string{"resourcemanager.projects.setIamPolicy"}},
		{ID: "gcp-privesc-02", Technique: TechniqueGCPActAsCreateInstance, Severity: SeverityCritical,
			Description:     "Launch a Compute instance with a privileged service account for credential theft",
			RequiredActions: []string{"iam.serviceAccounts.actAs", "compute.instances.create"}},
		{ID: "gcp-privesc-03", Technique: TechniqueGCPGetAccessToken, Severity: SeverityCritical,
			Description:     "Generate an access token for a service account to impersonate it directly",
			RequiredActions: []string{"iam.serviceAccounts.getAccessToken"}},
		{ID: "gcp-privesc-04", Technique: TechniqueGCPImplicitDelegation, Severity: SeverityCritical,
			Description:     "Chain service account impersonation via implicit delegation",
			RequiredActions: []string{"iam.serviceAccounts.implicitDelegation"}},
		{ID: "gcp-privesc-05", Technique: TechniqueGCPCreateSAKey, Severity: SeverityCritical,
			Description:     "Create a user-managed key for a service account to obtain persistent credentials",
			RequiredActions: []string{"iam.serviceAccountKeys.create"}},
		{ID: "gcp-privesc-06", Technique: TechniqueGCPActAsCloudFunction, Severity: SeverityCritical,
			Description:     "Deploy a Cloud Function with a privileged service account for code execution",
			RequiredActions: []string{"iam.serviceAccounts.actAs", "cloudfunctions.functions.create"}},
		{ID: "gcp-privesc-07", Technique: TechniqueGCPActAsCloudRun, Severity: SeverityCritical,
			Description:     "Deploy a Cloud Run service with a privileged service account",
			RequiredActions: []string{"iam.serviceAccounts.actAs", "run.services.create"}},
		{ID: "gcp-privesc-08", Technique: TechniqueGCPSetMetadata, Severity: SeverityHigh,
			Description:     "Inject SSH keys or a startup script into a Compute instance via metadata",
			RequiredActions: []string{"compute.instances.setMetadata"}},
		{ID: "gcp-privesc-09", Technique: TechniqueGCPSetCommonMetadata, Severity: SeverityCritical,
			Description:     "Inject project-wide SSH keys via project metadata, gaining access to all instances",
			RequiredActions: []string{"compute.projects.setCommonInstanceMetadata"}},
		{ID: "gcp-privesc-10", Technique: TechniqueGCPUpdateRole, Severity: SeverityCritical,
			Description:     "Add permissions to an existing custom IAM role to escalate its privileges",
			RequiredActions: []string{"iam.roles.update"}},
		{ID: "gcp-privesc-11", Technique: TechniqueGCPSetOrgPolicy, Severity: SeverityCritical,
			Description:     "Disable organization policy constraints to bypass security controls",
			RequiredActions: []string{"orgpolicy.policy.set"}},
		{ID: "gcp-privesc-12", Technique: TechniqueGCPDeploymentManager, Severity: SeverityHigh,
			Description:     "Create a Deployment Manager deployment that operates with the project's Google API service account",
			RequiredActions: []string{"deploymentmanager.deployments.create"}},
		{ID: "gcp-privesc-13", Technique: TechniqueGCPBucketSetIAMPolicy, Severity: SeverityHigh,
			Description:     "Modify a Cloud Storage bucket IAM policy to grant self access to sensitive data",
			RequiredActions: []string{"storage.buckets.setIamPolicy"}},
		{ID: "gcp-privesc-14", Technique: TechniqueGCPSignBlob, Severity: SeverityCritical,
			Description:     "Sign arbitrary blobs as a service account to forge authentication tokens",
			RequiredActions: []string{"iam.serviceAccounts.signBlob"}},
		{ID: "gcp-privesc-15", Technique: TechniqueGCPSetServiceAccount, Severity: SeverityHigh,
			Description:     "Change a VM's service account to escalate via the new SA's permissions",
			RequiredActions: []string{"compute.instances.setServiceAccount", "iam.serviceAccounts.actAs"}},
		{ID: "gcp-privesc-16", Technique: TechniqueGCPUpdateCloudFunction, Severity: SeverityHigh,
			Description:     "Update a Cloud Function's code to execute as the function's service account",
			RequiredActions: []string{"iam.serviceAccounts.actAs", "cloudfunctions.functions.update"}},
		{ID: "gcp-privesc-17", Technique: TechniqueGCPGKETakeover, Severity: SeverityCritical,
			Description:     "Update GKE cluster configuration and retrieve admin credentials for cluster takeover",
			RequiredActions: []string{"container.clusters.update", "container.clusters.getCredentials"}},
		{ID: "gcp-privesc-18", Technique: TechniqueGCPHMACKeyCreate, Severity: SeverityMedium,
			Description:     "Create HMAC keys for persistent, key-based access to Cloud Storage",
			RequiredActions: []string{"storage.hmacKeys.create"}},
	}
}
