package enrich

import (
	"encoding/json"
	"fmt"
)

// BandsJSONPath is where cmd/scoreband-gen writes ExportBandsJSON, relative to
// the repo root. The frontend reads every score→band boundary from it.
const BandsJSONPath = "frontend/src/generated/score-bands.json"

type exportBand struct {
	Band     Band `json:"band"`
	MinScore int  `json:"min_score"`
}

type exportBandsDoc struct {
	Comment string       `json:"//"`
	Bands   []exportBand `json:"bands"`
}

// ExportBandsJSON renders the bands, highest first, each with the lowest score
// bandFor places in it.
func ExportBandsJSON() ([]byte, error) {
	doc := exportBandsDoc{
		Comment: "GENERATED by cmd/scoreband-gen from internal/app/enrich — do not edit",
		Bands: []exportBand{
			{BandPage, ThresholdPage},
			{BandHigh, ThresholdHigh},
			{BandPipeline, ThresholdPipeline},
			{BandMonitor, 0},
		},
	}
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("ExportBandsJSON: %w", err)
	}
	return append(b, '\n'), nil
}
