package ciem

// AzurePrivescRules returns the full catalog of Azure / Entra ID privilege
// escalation detection rules, covering both Azure RBAC and Entra ID directory
// roles / application permissions.
func AzurePrivescRules() []PrivescRule {
	return []PrivescRule{
		{ID: "azure-privesc-01", Technique: TechniqueAzureRoleAssignmentWrite, Severity: SeverityCritical,
			Description:     "Create role assignments to grant Owner or Contributor role to any principal",
			RequiredActions: []string{"Microsoft.Authorization/roleAssignments/write"}},
		{ID: "azure-privesc-02", Technique: TechniqueAzureRoleDefinitionWrite, Severity: SeverityCritical,
			Description:     "Create or modify a custom role definition with wildcard permissions",
			RequiredActions: []string{"Microsoft.Authorization/roleDefinitions/write"}},
		{ID: "azure-privesc-03", Technique: TechniqueAzureVMRunCommand, Severity: SeverityHigh,
			Description:     "Execute commands on a VM to use its managed identity for credential theft",
			RequiredActions: []string{"Microsoft.Compute/virtualMachines/runCommand/action"}},
		{ID: "azure-privesc-04", Technique: TechniqueAzureVMExtensionWrite, Severity: SeverityHigh,
			Description:     "Install a custom script extension on a VM to execute code with its managed identity",
			RequiredActions: []string{"Microsoft.Compute/virtualMachines/extensions/write"}},
		{ID: "azure-privesc-05", Technique: TechniqueAzureKeyVaultAccessPolicy, Severity: SeverityHigh,
			Description:     "Modify Key Vault access policies to grant self access to secrets, keys, and certificates",
			RequiredActions: []string{"Microsoft.KeyVault/vaults/accessPolicies/write"}},
		{ID: "azure-privesc-06", Technique: TechniqueAzureUserAssignedIdentity, Severity: SeverityHigh,
			Description:     "Assign a user-assigned managed identity with elevated permissions to a resource",
			RequiredActions: []string{"Microsoft.ManagedIdentity/userAssignedIdentities/assign/action", "Microsoft.Compute/virtualMachines/write"}},
		{ID: "azure-privesc-07", Technique: TechniqueAzureARMDeployment, Severity: SeverityHigh,
			Description:     "Deploy an ARM template that creates resources with elevated permissions",
			RequiredActions: []string{"Microsoft.Resources/deployments/write"}},
		{ID: "azure-privesc-08", Technique: TechniqueAzureAppReadWriteAll, Severity: SeverityCritical,
			Description:     "Create or modify an application registration and grant it admin-consented API permissions",
			RequiredActions: []string{"Application.ReadWrite.All"}},
		{ID: "azure-privesc-09", Technique: TechniqueAzureAppRoleAssignment, Severity: SeverityCritical,
			Description:     "Grant application roles (app-only permissions) to a service principal",
			RequiredActions: []string{"AppRoleAssignment.ReadWrite.All"}},
		{ID: "azure-privesc-10", Technique: TechniqueAzureDirectoryRoleWrite, Severity: SeverityCritical,
			Description:     "Assign Entra ID directory roles (Global Admin, Privileged Role Admin) to any principal",
			RequiredActions: []string{"RoleManagement.ReadWrite.Directory"}},
		{ID: "azure-privesc-11", Technique: TechniqueAzureGroupMemberWrite, Severity: SeverityHigh,
			Description:     "Add self or a controlled principal to a privileged security group",
			RequiredActions: []string{"GroupMember.ReadWrite.All"}},
		{ID: "azure-privesc-12", Technique: TechniqueAzureServicePrincipalSecret, Severity: SeverityCritical,
			Description:     "Add a client secret or certificate to an existing service principal for persistent access",
			RequiredActions: []string{"Application.ReadWrite.All", "ServicePrincipalEndpoint.ReadWrite.All"}},
		{ID: "azure-privesc-13", Technique: TechniqueAzureOAuthGrant, Severity: SeverityCritical,
			Description:     "Create delegated permission grants (OAuth2 consent) on behalf of all users",
			RequiredActions: []string{"DelegatedPermissionGrant.ReadWrite.All"}},
		{ID: "azure-privesc-14", Technique: TechniqueAzureUserWriteRoleAssign, Severity: SeverityCritical,
			Description:     "Create a new Entra ID user and assign it a privileged directory role",
			RequiredActions: []string{"User.ReadWrite.All", "RoleManagement.ReadWrite.Directory"}},
		{ID: "azure-privesc-15", Technique: TechniqueAzureOwnerSubscription, Severity: SeverityCritical,
			Description:     "Owner role at subscription scope grants full control over all resources",
			RequiredActions: []string{"*/read", "*/write", "*/delete", "Microsoft.Authorization/roleAssignments/write"}},
		{ID: "azure-privesc-16", Technique: TechniqueAzureAKSAdminCreds, Severity: SeverityHigh,
			Description:     "Retrieve AKS cluster admin credentials for full Kubernetes control plane access",
			RequiredActions: []string{"Microsoft.ContainerService/managedClusters/listClusterAdminCredential/action"}},
		{ID: "azure-privesc-17", Technique: TechniqueAzureStorageListKeys, Severity: SeverityHigh,
			Description:     "List storage account keys to gain full data-plane access to blobs, queues, and tables",
			RequiredActions: []string{"Microsoft.Storage/storageAccounts/listKeys/action"}},
		{ID: "azure-privesc-18", Technique: TechniqueAzureSQLAdminWrite, Severity: SeverityHigh,
			Description:     "Set self as Azure SQL server administrator for full database access",
			RequiredActions: []string{"Microsoft.Sql/servers/administrators/write"}},
		{ID: "azure-privesc-19", Technique: TechniqueAzureLockDelete, Severity: SeverityMedium,
			Description:     "Delete resource locks to enable destruction of protected resources",
			RequiredActions: []string{"Microsoft.Authorization/locks/delete"}},
		{ID: "azure-privesc-20", Technique: TechniqueAzureAppServicePublish, Severity: SeverityHigh,
			Description:     "Retrieve App Service publish credentials to deploy arbitrary code",
			RequiredActions: []string{"Microsoft.Web/sites/publishxml/action"}},
	}
}
