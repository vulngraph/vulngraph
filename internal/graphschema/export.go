package graphschema

import "encoding/json"

// exportRel is the JSON shape of a rel table in graph-schema.json.
type exportRel struct {
	Name   string `json:"name"`
	From   string `json:"from"`
	To     string `json:"to"`
	Loaded bool   `json:"loaded"`
	Expand bool   `json:"expand"`
	Doc    string `json:"doc"`
}

// exportEdgeType is the JSON shape of an edge_type in graph-schema.json.
type exportEdgeType struct {
	Type string `json:"type"`
	Rel  string `json:"rel,omitempty"`
	Tier Tier   `json:"tier"`
}

type exportDoc struct {
	Comment   string           `json:"//"`
	Rels      []exportRel      `json:"rels"`
	EdgeTypes []exportEdgeType `json:"edge_types"`
}

// ExportJSON renders the registry as the deterministic artifact committed at
// frontend/src/generated/graph-schema.json. The frontend's vitest pins every
// rel label used in preset Cypher strings to the loaded set here, so a preset
// referencing an unloaded rel fails CI instead of silently rendering empty.
// Regenerate with `go run ./cmd/graphschema-gen`; TestExportJSONIsFresh fails
// when the committed file is stale.
func ExportJSON() ([]byte, error) {
	doc := exportDoc{
		Comment: "GENERATED by cmd/graphschema-gen from internal/graphschema — do not edit",
	}
	for _, r := range Rels {
		doc.Rels = append(doc.Rels, exportRel{r.Name, r.From, r.To, r.Loaded, r.Expand, r.Doc})
	}
	for _, e := range EdgeTypes {
		doc.EdgeTypes = append(doc.EdgeTypes, exportEdgeType{e.Type, e.Rel, e.Tier})
	}
	b, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(b, '\n'), nil
}
