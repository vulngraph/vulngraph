// Package frameworks maps compliance-framework requirements (NIST SP 800-53
// Rev. 5, PCI DSS 4.0, SOC 2, ISO/IEC 27001:2022 Annex A, the HIPAA
// Security Rule) to graph's benchmark controls, and through the benchmark
// matrices to registry checks (ADR 093).
//
// A requirement names benchmark controls ("aws-fsbp/IAM.6",
// "cis-aws-foundations/2.3"), never checks: which checks evidence a
// control is the matrix's answer, so a check added to a matrix row reaches
// every requirement mapped to that row without regenerating anything here.
//
// Files hold requirement IDs and short titles only. ISO, PCI and AICPA text
// is copyrighted: those titles are paraphrased by hand. NIST and HIPAA are
// US government works and keep their own titles.
package frameworks

import (
	"bytes"
	"embed"
	"errors"
	"fmt"
	"io/fs"
	"os"
	"sort"
	"strconv"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/vulngraph/vulngraph/internal/checks/benchmarks"
)

//go:embed *.yaml
var files embed.FS

// Dir is this package's directory relative to the repository root, where the
// generator rewrites the mapping files.
const Dir = "internal/checks/frameworks"

// maxTitleWords keeps a title a paraphrase rather than standard text.
const maxTitleWords = 12

// Framework is one compliance framework's requirement list.
type Framework struct {
	ID      string `yaml:"framework"`
	Name    string `yaml:"name"`
	Version string `yaml:"version"`
	// Sources attributes where the mapping comes from.
	Sources      []string      `yaml:"sources"`
	Requirements []Requirement `yaml:"requirements"`
}

// Requirement is one requirement and the benchmark controls mapped to it.
type Requirement struct {
	ID    string `yaml:"id"`
	Title string `yaml:"title"`
	// Unjoined counts the source mappings (a Prowler check, an AWS related
	// FSBP control) that reach no benchmark-matrix row. Above zero, graph
	// evaluates only part of what the source counts as evidence, so the
	// requirement can be failing or unknown but never passing.
	Unjoined int      `yaml:"unjoined,omitempty"`
	Controls []string `yaml:"controls"`
}

// Ref splits a control reference into benchmark and control ID.
func Ref(ref string) (benchmark, control string, ok bool) {
	return strings.Cut(ref, "/")
}

// FileName is a framework's mapping file name.
func FileName(id string) string { return strings.ReplaceAll(id, "-", "_") + ".yaml" }

// Load parses the embedded mapping files, in a stable framework order.
func Load() ([]Framework, error) { return load(files) }

// LoadDir parses the mapping files in dir (the generator reads the committed
// files to keep their hand-written titles).
func LoadDir(dir string) ([]Framework, error) { return load(os.DirFS(dir)) }

func load(fsys fs.FS) ([]Framework, error) {
	names, err := fs.Glob(fsys, "*.yaml")
	if err != nil {
		return nil, fmt.Errorf("load: %w", err)
	}
	out := make([]Framework, 0, len(names))
	for _, name := range names {
		raw, err := fs.ReadFile(fsys, name)
		if err != nil {
			return nil, fmt.Errorf("load: %s: %w", name, err)
		}
		fw, err := Parse(raw)
		if err != nil {
			return nil, fmt.Errorf("load: %s: %w", name, err)
		}
		out = append(out, fw)
	}
	sort.Slice(out, func(i, j int) bool { return out[i].ID < out[j].ID })
	return out, nil
}

// Parse decodes one mapping file strictly: a misspelt key must not parse as
// a requirement with no controls.
func Parse(raw []byte) (Framework, error) {
	dec := yaml.NewDecoder(bytes.NewReader(raw))
	dec.KnownFields(true)
	var fw Framework
	if err := dec.Decode(&fw); err != nil {
		return Framework{}, fmt.Errorf("Parse: %w", err)
	}
	return fw, nil
}

// Encode renders a framework as its committed file: one requirement per
// line, controls sorted, so a regeneration diff reads requirement by
// requirement.
func Encode(fw Framework) []byte {
	var w bytes.Buffer
	w.WriteString("# Generated by `go run ./cmd/benchmark-watch -frameworks -update` (ADR 093).\n")
	w.WriteString("# Requirement IDs and short titles only; copyrighted titles are paraphrased by hand\n")
	w.WriteString("# and kept across regenerations. Controls are benchmark-matrix rows, not checks.\n")
	fmt.Fprintf(&w, "framework: %s\nname: %s\nversion: %s\nsources:\n", fw.ID, strconv.Quote(fw.Name), strconv.Quote(fw.Version))
	for _, s := range fw.Sources {
		fmt.Fprintf(&w, "  - %s\n", strconv.Quote(s))
	}
	w.WriteString("requirements:\n")
	for _, r := range fw.Requirements {
		refs := append([]string(nil), r.Controls...)
		sort.Strings(refs)
		quoted := make([]string, len(refs))
		for i, c := range refs {
			quoted[i] = strconv.Quote(c)
		}
		unjoined := ""
		if r.Unjoined > 0 {
			unjoined = fmt.Sprintf(" unjoined: %d,", r.Unjoined)
		}
		fmt.Fprintf(&w, "  - {id: %s, title: %s,%s controls: [%s]}\n", strconv.Quote(r.ID), strconv.Quote(r.Title), unjoined, strings.Join(quoted, ", "))
	}
	return w.Bytes()
}

// Validate reports every structural problem: missing header fields,
// duplicate requirement IDs, a title that is empty or too long to be a
// paraphrase, and a control reference that names no matrix row.
func Validate(fw Framework, bs []benchmarks.Benchmark) error {
	var errs []error
	if fw.ID == "" || fw.Name == "" || fw.Version == "" || len(fw.Sources) == 0 {
		errs = append(errs, fmt.Errorf("%s: header incomplete", fw.ID))
	}
	if len(fw.Requirements) == 0 {
		errs = append(errs, fmt.Errorf("%s: no requirements", fw.ID))
	}
	rows := controlIndex(bs)
	seen := map[string]bool{}
	for _, r := range fw.Requirements {
		where := fw.ID + " " + r.ID
		if r.ID == "" || seen[r.ID] {
			errs = append(errs, fmt.Errorf("%s: empty or duplicate requirement id", where))
		}
		seen[r.ID] = true
		if r.Unjoined < 0 {
			errs = append(errs, fmt.Errorf("%s: negative unjoined count", where))
		}
		if n := len(strings.Fields(r.Title)); n == 0 || n > maxTitleWords {
			errs = append(errs, fmt.Errorf("%s: title must be 1-%d words, got %d", where, maxTitleWords, n))
		}
		dup := map[string]bool{}
		for _, ref := range r.Controls {
			if dup[ref] {
				errs = append(errs, fmt.Errorf("%s: control %q listed twice", where, ref))
			}
			dup[ref] = true
			if _, ok := rows[ref]; !ok {
				errs = append(errs, fmt.Errorf("%s: control %q is no benchmark matrix row", where, ref))
			}
		}
	}
	return errors.Join(errs...)
}

// MappedControl is one matrix row a requirement maps, with the benchmark's
// providers (which inventory can evidence it).
type MappedControl struct {
	Benchmark string
	Providers []string
	benchmarks.Control
}

// Ref is the control's reference string.
func (m MappedControl) Ref() string { return m.Benchmark + "/" + m.ID }

// controlIndex maps every "benchmark/control" reference to its row.
func controlIndex(bs []benchmarks.Benchmark) map[string]MappedControl {
	out := map[string]MappedControl{}
	for _, b := range bs {
		for _, c := range b.Controls {
			out[b.ID+"/"+c.ID] = MappedControl{Benchmark: b.ID, Providers: b.Providers, Control: c}
		}
	}
	return out
}

// Index resolves control references against the matrices.
type Index map[string]MappedControl

// NewIndex builds the reference index over the matrices.
func NewIndex(bs []benchmarks.Benchmark) Index { return controlIndex(bs) }

// Controls resolves a requirement's references; an unresolvable one (a
// matrix row since removed) is returned in missing rather than dropped, so
// a caller can count it as a gap.
func (ix Index) Controls(r Requirement) (found []MappedControl, missing []string) {
	for _, ref := range r.Controls {
		if c, ok := ix[ref]; ok {
			found = append(found, c)
		} else {
			missing = append(missing, ref)
		}
	}
	return found, missing
}

// HasCheck reports whether any control the requirement maps lists a check.
func (ix Index) HasCheck(r Requirement) bool {
	found, _ := ix.Controls(r)
	for _, c := range found {
		if len(c.CheckIDs) > 0 {
			return true
		}
	}
	return false
}

// CanPass reports whether the requirement has no structural gap: it maps at
// least one control, every reference resolves to a covered control, and every
// source mapping joins (Unjoined == 0). It mirrors the static half of the
// compliance rollup (rollupRequirement in internal/app/compliance), which
// marks any other requirement unknown once its controls are in scope.
func (ix Index) CanPass(r Requirement) bool {
	if len(r.Controls) == 0 || r.Unjoined > 0 {
		return false
	}
	found, missing := ix.Controls(r)
	if len(missing) > 0 {
		return false
	}
	for _, c := range found {
		if c.Status != benchmarks.StatusCovered {
			return false
		}
	}
	return true
}
