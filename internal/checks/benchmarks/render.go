package benchmarks

import (
	"fmt"
	"sort"
	"strings"
)

// RenderSummary is the head of docs/cspm-coverage.md: the per-benchmark
// totals, with when benchmark-watch last checked each matrix against its
// upstream (internal/checks/coveragedoc assembles the document).
func RenderSummary(bs []Benchmark, snaps map[string]SourceSnapshot) string {
	var w strings.Builder
	w.WriteString("# CSPM benchmark coverage\n\n")
	w.WriteString("<!-- Generated by `go run ./cmd/cspm-coverage` from internal/checks/benchmarks/*.yaml, internal/checks/frameworks/*.yaml and the check registry. Do not edit. -->\n\n")
	w.WriteString("Vulngraph's CSPM mapped against public cloud benchmarks, control by control. ")
	w.WriteString("Statuses are a maintainer-declared mapping: `covered` means the listed registry check(s) are judged ")
	w.WriteString("to evaluate the control's condition; `partial` evaluates part of it; ")
	w.WriteString("`missing` is evaluable from cloud APIs but has no check yet; `not_applicable` is outside what an ")
	w.WriteString("API-driven scanner can see; `manual` needs human evidence. ")
	w.WriteString("Tests check that every cited check exists for the benchmark's provider, and a scheduled job compares ")
	w.WriteString("control IDs with the pinned upstream list (ADR 092); nothing checks that each check is equivalent to its control. ")
	w.WriteString("Control IDs and paraphrased titles only — no benchmark text is reproduced.\n\n")
	w.WriteString("\"Checked against upstream\" is when `go run ./cmd/benchmark-watch -update` last compared the matrix's ")
	w.WriteString("control IDs with the public list it is pinned to (ADR 092).\n\n")

	w.WriteString("| Benchmark | Version | Controls | Covered | Partial | Missing | N/A | Manual | Checked against upstream |\n")
	w.WriteString("|---|---|---:|---:|---:|---:|---:|---:|---|\n")
	for _, b := range bs {
		n := b.Counts()
		fmt.Fprintf(&w, "| %s | %s | %d | %d | %d | %d | %d | %d | %s |\n", b.Name, b.Version, len(b.Controls),
			n[StatusCovered], n[StatusPartial], n[StatusMissing], n[StatusNotApplicable], n[StatusManual], checkedCell(snaps, b.ID))
	}
	return w.String()
}

func checkedCell(snaps map[string]SourceSnapshot, id string) string {
	s, ok := snaps[id]
	if !ok {
		return "never"
	}
	cell := s.Checked + " (" + s.Source
	if !s.Exact {
		cell += ", nearest published version " + s.SourceVersion
	}
	return cell + ")"
}

// RenderGaps lists each benchmark's missing and partial controls.
func RenderGaps(bs []Benchmark) string {
	var w strings.Builder
	for _, b := range bs {
		fmt.Fprintf(&w, "\n## %s %s\n\n", b.Name, b.Version)
		writeGrouped(&w, "Missing", b, StatusMissing)
		writeGrouped(&w, "Partial", b, StatusPartial)
	}
	return w.String()
}

// writeGrouped lists the controls with one status, grouped by service.
func writeGrouped(w *strings.Builder, heading string, b Benchmark, s Status) {
	byService := map[string][]Control{}
	for _, c := range b.Controls {
		if c.Status == s {
			byService[c.Service] = append(byService[c.Service], c)
		}
	}
	if len(byService) == 0 {
		return
	}
	services := make([]string, 0, len(byService))
	for svc := range byService {
		services = append(services, svc)
	}
	sort.Strings(services)
	fmt.Fprintf(w, "### %s\n\n", heading)
	for _, svc := range services {
		fmt.Fprintf(w, "**%s**\n\n", svc)
		for _, c := range byService[svc] {
			fmt.Fprintf(w, "- `%s` %s — %s\n", c.ID, c.Title, oneLine(c.Reason))
		}
		w.WriteString("\n")
	}
}

func oneLine(s string) string { return strings.Join(strings.Fields(s), " ") }
